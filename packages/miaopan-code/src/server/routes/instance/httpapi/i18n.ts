export type Language = "zh-CN" | "en"
export type MessageKey = keyof typeof messages
export function resolveLanguage(input: unknown): Language {
  return input === "en" ? "en" : "zh-CN"
}
export function t(
  language: Language | undefined,
  key: MessageKey,
  parameters: Record<string, string | number | undefined> = {},
) {
  return messages[key][resolveLanguage(language)].replace(/{{(\w+)}}/g, (_, name: string) =>
    String(parameters[name] ?? ""),
  )
}
export function text(
  language: Language | undefined,
  key: MessageKey,
  parameters: Record<string, string | number | undefined> = {},
) {
  return t(language, key, parameters)
}
export function localizeText(language: Language | undefined, text: string) {
  const entry = Object.values(messages).find((value) => value["zh-CN"] === text || value.en === text)
  return entry?.[resolveLanguage(language)] ?? text
}
